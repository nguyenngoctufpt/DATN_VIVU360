export function getSettingsText(language) {
  return SETTINGS_TEXT[language] || SETTINGS_TEXT.vi;
}

export function getLocalizedLabel(option, language) {
  if (!option) return '';
  if (typeof option === 'string') return option;
  if (typeof option.label === 'string') return option.label;
  return option.label?.[language] || option.label?.vi || option.value || '';
}

export function findLocalizedValue(options, value, language) {
  return getLocalizedLabel(options.find((item) => item.value === value), language);
}
